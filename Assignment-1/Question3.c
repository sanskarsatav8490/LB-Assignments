// Question: Accept one number from the user. If the number is less than 10, print "Hello"; otherwise, print "Demo".

#include <stdio.h>

void Display(int iNo)
{
    if (iNo < 10)
    {
        printf("Hello");
    }
    else
    {
        printf("Demo");
    }
}

int main()
{
    int iValue = 0;

    printf("Enter number: ");
    scanf("%d", &iValue);

    Display(iValue);

    return 0;
}